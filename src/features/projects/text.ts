/** Label for a backend value (stage, unit type, sentiment); falls back to the value in sentence case. */
export function label(map: Record<string, string>, value: string | null | undefined): string {
  if (!value) return '';
  return map[value.toLowerCase()] ?? value.charAt(0).toUpperCase() + value.slice(1).replace(/_/g, ' ');
}

/** Tone class for a stage or status badge, from the value the API sent. */
export function toneOf(value: string | null | undefined): 'is-good' | 'is-bad' | 'is-wait' | 'is-plain' {
  const v = (value ?? '').toLowerCase();
  if (v === 'completed' || v === 'registered' || v === 'approved') return 'is-good';
  if (v === 'lapsed' || v === 'revoked' || v === 'rejected') return 'is-bad';
  if (v === 'under_construction' || v === 'new_launch' || v === 'pre_launch' || v === 'near_possession' || v === 'delayed' || v === 'pending') return 'is-wait';
  return 'is-plain';
}

/** `1,250` with the unit word, or an em dash when the number is missing. */
export const withUnit = (value: number | null | undefined, unit: string, locale: Locale): string =>
  value === null || value === undefined ? '—' : `${formatNum(value, locale, { maximumFractionDigits: 2 })} ${unit}`;
