export type ChatCopy = typeof en;
export const chatCopy = (locale: Locale): ChatCopy => byLocale(locale, { en, hi });

/** "in_progress" -> "In progress". Never blank for a non-empty value. */
export function humanize(raw: string): string {
  const s = raw.replace(/[_\s]+/g, ' ').trim();
  return s ? s.charAt(0).toUpperCase() + s.slice(1) : '';
}

/** The label of a backend enum value (status, urgency, category, payment method). Unknown values are humanized, never blank. */
export function valueLabel(c: ChatCopy, raw: string | null | undefined): string {
  if (!raw) return '';
  const key = raw.trim().toLowerCase().replace(/[\s-]+/g, '_');
  return Object.hasOwn(c.values, key) ? c.values[key]! : humanize(raw);
}
