export type DhText = Text;
export const text = (locale: Locale): Text => TEXT[locale];

/** Label for a backend value (property type, status); falls back to the value in sentence case. */
export function label(map: Record<string, string>, value: string | null | undefined): string {
  if (!value) return '';
  return map[value.toLowerCase()] ?? value.charAt(0).toUpperCase() + value.slice(1).replace(/_/g, ' ');
}
