/**
 * Legacy URL rules. Every old URL must return 200 or 301. These rules run in
 * middleware for on-demand requests (prerendered files never need them).
 * Returns the target path, or null when the path is already canonical.
 */
import localityRedirects from '@/data/locality-redirects.json';
import { localeFromPath, localizePath, stripLocale } from '@/lib/i18n/locale';

const EXACT: Record<string, string> = {
  '/property': '/properties',
  '/projects': '/project',
  '/truth': '/vs',
  '/data-hub/circle-rates': '/circle-rates',
  '/data-hub/rera-projects': '/rera-projects',
  '/data-hub/bank-auctions': '/bank-auctions',
  '/property-sidebar': '/properties',
  '/add-new-listing': '/post-property',
  '/home-two': '/',
  '/home-three': '/',
};

/** URL words for property types that have one canonical landing segment. */
export const TYPE_ALIASES: Record<string, string> = {
  apartment: 'flats',
  apartments: 'flats',
  flat: 'flats',
  house: 'independent-house',
  houses: 'independent-house',
  'independent-houses': 'independent-house',
  plot: 'plots',
  land: 'plots',
  office: 'office-space',
  offices: 'office-space',
  villas: 'villa',
  shops: 'shop',
  'builder-floors': 'builder-floor',
};

/**
 * Scraped locality slugs ("projects-in-x-gurgaon") to their real twin ("x-gurgaon"). Generated by
 * scripts/data/build-locality-redirects.mjs. Keys cover every slug form the page accepts, so it is one hop.
 * Undo: delete entries in src/data/locality-redirects.json.
 */
const LOCALITY_TWIN: Record<string, string> = localityRedirects;

const INTENTS = new Set(['buy', 'rent', 'pg']);
const PG_TYPES = new Set(['independent-house', 'builder-floor', 'villa', 'plots', 'office-space', 'shop']);

export function legacyRedirect(pathname: string): string | null {
  let path = pathname;
  // No trailing slash, and lower case (except the API and files with extensions).
  if (path.length > 1 && path.endsWith('/')) path = path.replace(/\/+$/, '') || '/';
  // Percent escapes (%E0%A4%95) stay as they are: browsers send them in upper case.
  if (/[A-Z]/.test(path.replace(/%[0-9A-F]{2}/gi, '')) && !path.startsWith('/api/')) {
    path = path.replace(/(%[0-9A-F]{2})|[^%]+/gi, (m, esc: string | undefined) => esc ?? m.toLowerCase());
  }

  const locale = localeFromPath(path);
  let rest = stripLocale(path);

  if (EXACT[rest]) rest = EXACT[rest]!;

  const parts = rest.split('/').filter(Boolean);
  // City slug: gurugram -> gurgaon.
  if (parts[0] === 'gurugram') parts[0] = 'gurgaon';
  // Landing type aliases at any depth: /:city/:intent/:type[/...]
  if (parts.length >= 3 && INTENTS.has(parts[1]!) && TYPE_ALIASES[parts[2]!]) parts[2] = TYPE_ALIASES[parts[2]!]!;
  // PG landings always use "flats".
  if (parts.length >= 3 && parts[1] === 'pg' && parts[2] !== 'flats' && !['budget', 'amenity'].includes(parts[2]!)) {
    if (PG_TYPES.has(parts[2]!)) parts[2] = 'flats';
  }
  // Scraped locality pages: /locality/:slug and /locality/:slug/:intent go to the real twin. The intent page sends
  // any word but buy or rent to /buy, so that is done here too (no second hop).
  if (parts[0] === 'locality' && (parts.length === 2 || parts.length === 3) && Object.hasOwn(LOCALITY_TWIN, parts[1]!)) {
    parts[1] = LOCALITY_TWIN[parts[1]!]!;
    if (parts[2] && parts[2] !== 'buy' && parts[2] !== 'rent') parts[2] = 'buy';
  }
  rest = parts.length ? `/${parts.join('/')}` : '/';

  const target = localizePath(rest, locale);
  return target === pathname ? null : target;
}

/** The 301 Location for a request: the target path plus the original query string, or null when no rule applies. */
export function redirectLocation(pathname: string, search = ''): string | null {
  const target = legacyRedirect(pathname);
  return target ? target + search : null;
}
